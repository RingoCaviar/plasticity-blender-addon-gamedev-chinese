def _catalog():
    # UI text, operator tooltips and RNA properties use distinct translation
    # contexts in Blender. Register every relevant context so descriptions in
    # tooltips are translated as well as panel labels.
    messages = {
        (context, source): target
        for context in ("*", "Operator", "Property")
        for source, target in _ZH.items()
    }
    # Blender 4.x installations may expose either locale identifier.
    return {"zh_HANS": messages, "zh_CN": messages}


def report(receiver, level, message):
    """Translate a user-facing report immediately before Blender displays it."""
    receiver.report(level, bpy.app.translations.pgettext_iface(message))


def report_template(receiver, level, template, **values):
    """Translate a report template before substituting dynamic values."""
    receiver.report(level, bpy.app.translations.pgettext_iface(template).format(**values))


def register():
    try:
        bpy.app.translations.unregister(_ADDON_KEY)
    except RuntimeError:
        pass
    bpy.app.translations.register(_ADDON_KEY, _catalog())


def unregister():
    try:
        bpy.app.translations.unregister(_ADDON_KEY)
    except RuntimeError:
        pass
